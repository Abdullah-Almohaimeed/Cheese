// Generates src/styles/tokens.css and src/styles/components.css from the design system files in design/.
// Run with: npx tsx scripts/build-css.ts
import { readFileSync, writeFileSync } from "node:fs";

type ColorToken = { name: string; value: Record<string, string> };
type Plain = { name: string; value: string };

const tokens = JSON.parse(readFileSync("design/tokens.json", "utf8"));

const colors: ColorToken[] = tokens.color.tokens;
const byName = new Map(colors.map((c) => [c.name, c]));

function resolve(theme: string, name: string, seen = new Set<string>()): string {
  const tok = byName.get(name);
  if (!tok) throw new Error(`Unknown color token ${name}`);
  if (seen.has(name)) throw new Error(`Alias cycle at ${name}`);
  seen.add(name);
  const raw = tok.value[theme] ?? tok.value.light;
  const alias = raw.match(/^\{(.+)\}$/);
  return alias ? resolve(theme, alias[1], seen) : raw;
}

function colorBlock(theme: string, indent: string): string {
  return colors.map((c) => `${indent}--${c.name}: ${resolve(theme, c.name)};`).join("\n");
}

function plainBlock(group: { tokens: Plain[] }): string {
  return group.tokens.map((t) => `  --${t.name}: ${t.value};`).join("\n");
}

const fam = tokens.type.families;
const css = `/* Generated by scripts/build-css.ts from design/tokens.json. Do not edit. */
:root {
  color-scheme: light dark;
${colorBlock("light", "  ")}
${plainBlock(tokens.spacing)}
${plainBlock(tokens.radius)}
${plainBlock(tokens.size)}
  --font-display: ${fam.display};
  --font-sans: ${fam.sans};
}

@media (prefers-color-scheme: dark) {
  :root {
${colorBlock("dark", "    ")}
  }
}
`;
writeFileSync("src/styles/tokens.css", css);

let bundle = readFileSync("design/bundle.source.css", "utf8");
bundle = bundle.replace(/^@import url\([^)]*\);\n/m, "");
const cut = bundle.indexOf("/* Screen scaffolding");
if (cut > -1) bundle = bundle.slice(0, cut);
writeFileSync(
  "src/styles/components.css",
  "/* Copied from the Cheese design system (design/bundle.source.css) by scripts/build-css.ts. */\n" + bundle.trimEnd() + "\n",
);
console.log("wrote src/styles/tokens.css and src/styles/components.css");
